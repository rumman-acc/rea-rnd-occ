import { appendAudit } from "../../audit";
import { todayIsoDate } from "../../clock";
import { badRequest } from "../../http";
import { master } from "../../master";
import type { Store } from "../../store";
import type { EntryPatch, PlanEntry, SopCell, SopItem, SopResponse, SopRow } from "./types";

const PLAN_KEY = "sop:plan";
const HORIZON = 6;
const MAX_QTY = 1_000_000;
const MONTH_NAMES = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

interface PlanDoc {
  entries: Record<string, PlanEntry>;
}

/** The six months starting with the clock's current month. */
export function horizonMonths(): string[] {
  let y = Number(todayIsoDate().slice(0, 4));
  let m = Number(todayIsoDate().slice(5, 7));
  const out: string[] = [];
  for (let i = 0; i < HORIZON; i++) {
    out.push(`${y}-${String(m).padStart(2, "0")}`);
    if (++m > 12) {
      m = 1;
      y++;
    }
  }
  return out;
}

const monthLabel = (ym: string) => `${MONTH_NAMES[Number(ym.slice(5, 7)) - 1]} ${ym.slice(2, 4)}`;

/** Planning grain (our design): one routing model per series, named "<series> STD". */
export const modelOfSeries = (series: string) => `${series} STD`;

/** Series of a user-added model: first digit followed by "000" (the convention the page's Add Model uses). */
function seriesOfModel(model: string, known: Map<string, string>): string {
  const k = known.get(model);
  if (k !== undefined) return k;
  const d = /^\D*(\d)/.exec(model)?.[1];
  return d ? `${d}000` : "";
}

const emptyCells = (months: string[]): SopCell[] =>
  months.map((month) => ({ month, demand: 0, scheduled: 0, firm: 0, flex: 0, effective_supply: 0, gap: 0 }));

function finish(c: SopCell): SopCell {
  c.effective_supply = c.scheduled + c.firm + c.flex;
  c.gap = c.effective_supply - c.demand;
  return c;
}

const hasData = (cells: SopCell[]) => cells.some((c) => c.demand || c.scheduled || c.firm || c.flex);

/** Month index for a date; dates before the window fall into the first month, later ones are dropped (-1). */
function bucket(date: string, months: string[]): number {
  const ym = date.slice(0, 7);
  if (ym < months[0]) return 0;
  return months.indexOf(ym);
}

export function readPlan(store: Store): PlanDoc {
  return store.get<PlanDoc>(PLAN_KEY, () => ({ entries: {} }));
}

export function buildSop(store: Store): SopResponse {
  const months = horizonMonths();
  const fgs = master(store, "fg_items");
  const lines = master(store, "sales_lines");
  const orders = master(store, "production_orders");
  const plan = readPlan(store).entries;

  const fgModel = new Map(fgs.map((f) => [f.item_no, modelOfSeries(f.series)]));
  const modelSeries = new Map(fgs.map((f) => [modelOfSeries(f.series), f.series]));

  const itemCells = new Map<string, SopCell[]>();
  const cellsFor = (item: string) => {
    let c = itemCells.get(item);
    if (!c) itemCells.set(item, (c = emptyCells(months)));
    return c;
  };
  for (const l of lines) {
    const i = bucket(l.delivery_date, months);
    if (i >= 0) cellsFor(l.fg_item_no)[i].demand += l.quantity;
  }
  for (const o of orders) {
    if (o.status === "Finished") continue;
    const i = bucket(o.end_date, months);
    if (i >= 0) cellsFor(o.fg_item_no)[i].scheduled += o.quantity;
  }

  const models = new Set<string>(modelSeries.keys());
  for (const key of Object.keys(plan)) models.add(parseKey(key).model);

  const rows: SopRow[] = [...models].map((model) => {
    const cells = emptyCells(months);
    const items: SopItem[] = [];
    const available: SopRow["available_items"] = [];
    for (const fg of fgs.filter((f) => fgModel.get(f.item_no) === model)) {
      const ic = itemCells.get(fg.item_no) ?? emptyCells(months);
      ic.forEach((c, i) => {
        const p = plan[`${model}|${fg.item_no}_${c.month}`];
        c.firm = p?.firm ?? 0;
        c.flex = p?.flex ?? 0;
        finish(c);
        cells[i].demand += c.demand;
        cells[i].scheduled += c.scheduled;
      });
      if (hasData(ic)) items.push({ item_no: fg.item_no, description: fg.description, cells: ic });
      else available.push({ item_no: fg.item_no, description: fg.description });
    }
    cells.forEach((c) => {
      const p = plan[`${model}_${c.month}`];
      c.firm = p?.firm ?? 0;
      c.flex = p?.flex ?? 0;
      finish(c);
    });
    return { series: seriesOfModel(model, modelSeries), model, cells, items, available_items: available };
  });

  rows.sort((a, b) => (a.series || "~").localeCompare(b.series || "~") || a.model.localeCompare(b.model));
  return { months, rows, insights: insightsFor(rows, months) };
}

/** Deterministic planning observations (P): fixed rules over the sheet, not generated by a model. */
function insightsFor(rows: SopRow[], months: string[]): string[] {
  const out: string[] = [];
  const sum = (f: (c: SopCell) => number) => rows.reduce((s, r) => s + r.cells.reduce((t, c) => t + f(c), 0), 0);
  const demand = sum((c) => c.demand);
  const supply = sum((c) => c.effective_supply);
  out.push(
    demand === 0
      ? `No demand in the next ${months.length} months.`
      : `${months.length}-month demand ${demand} units vs plan ${supply} units (${Math.round((supply / demand) * 100)}% covered).`,
  );

  let short = 0;
  for (const r of rows.filter((x) => hasData(x.cells))) {
    const gaps = r.cells.filter((c) => c.gap < 0);
    if (gaps.length) {
      short++;
      const total = gaps.reduce((s, c) => s - c.gap, 0);
      out.push(
        `Model ${r.model}: shortfall of ${total} units across ${gaps.length} month${gaps.length === 1 ? "" : "s"}, first in ${monthLabel(gaps[0].month)}. Add a Firm or Flex plan to cover it.`,
      );
    }
  }
  for (const r of rows) {
    const net = r.cells.reduce((s, c) => s + c.gap, 0);
    if (net > 0) out.push(`Model ${r.model}: surplus of ${net} units over ${months.length} months; review the plan against demand.`);
  }
  if (short === 0) out.push("All models are covered by scheduled and planned supply.");
  return out;
}

export function parseKey(key: string): { model: string; item: string | null; month: string } {
  const m = /^(.+)_(\d{4}-\d{2})$/.exec(key);
  if (!m) throw badRequest(`Invalid plan key "${key}" (expected "<model>_<YYYY-MM>" or "<model>|<item>_<YYYY-MM>")`);
  const [model, item] = m[1].split("|");
  return { model: model.trim(), item: item === undefined ? null : item.trim(), month: m[2] };
}

function qty(v: unknown, key: string, field: string): number {
  if (typeof v !== "number" || !Number.isFinite(v) || v < 0 || v > MAX_QTY) {
    throw badRequest(`${field} for "${key}" must be a number between 0 and ${MAX_QTY}`);
  }
  return v;
}

export function savePlan(store: Store, entries: unknown, actor: string): { saved: number } {
  if (!entries || typeof entries !== "object" || Array.isArray(entries)) throw badRequest("entries must be an object");
  const months = horizonMonths();
  const items = new Set(master(store, "fg_items").map((f) => f.item_no));
  const parsed: [string, EntryPatch][] = [];
  for (const [key, raw] of Object.entries(entries as Record<string, unknown>)) {
    const k = parseKey(key);
    if (!k.model || k.model.length > 40) throw badRequest(`Model name in "${key}" must be 1-40 characters`);
    if (k.item !== null && !items.has(k.item)) throw badRequest(`Unknown item "${k.item}" in "${key}"`);
    if (!months.includes(k.month)) {
      throw badRequest(`Month ${k.month} in "${key}" is outside the planning window (${months[0]} to ${months[months.length - 1]})`);
    }
    if (raw === null) {
      parsed.push([key, null]);
      continue;
    }
    if (typeof raw !== "object" || Array.isArray(raw)) throw badRequest(`Entry for "${key}" must be an object or null`);
    const o = raw as Record<string, unknown>;
    if (o.firm === undefined && o.flex === undefined) throw badRequest(`Entry for "${key}" needs firm and/or flex`);
    const patch: { firm?: number; flex?: number } = {};
    if (o.firm !== undefined) patch.firm = qty(o.firm, key, "firm");
    if (o.flex !== undefined) patch.flex = qty(o.flex, key, "flex");
    parsed.push([key, patch]);
  }
  store.update<PlanDoc>(PLAN_KEY, () => ({ entries: {} }), (d) => {
    for (const [key, patch] of parsed) {
      if (patch === null) {
        delete d.entries[key];
        continue;
      }
      const next = { firm: patch.firm ?? d.entries[key]?.firm ?? 0, flex: patch.flex ?? d.entries[key]?.flex ?? 0 };
      if (next.firm === 0 && next.flex === 0) delete d.entries[key];
      else d.entries[key] = next;
    }
  });
  appendAudit(store, {
    source: "sop",
    actor,
    action: "sop.plan.save",
    detail: `${parsed.length} plan entr${parsed.length === 1 ? "y" : "ies"} saved: ${parsed
      .slice(0, 5)
      .map(([k]) => k)
      .join(", ")}${parsed.length > 5 ? ", ..." : ""}`,
  });
  return { saved: parsed.length };
}
